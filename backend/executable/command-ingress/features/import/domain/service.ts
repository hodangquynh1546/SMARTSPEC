/**
 * Structured design artifacts written by an external author (Claude through the MCP) instead of generated by
 * SmartSpec's own LLM call. Everything goes through the same rules as a person editing: it lands in the working version
 * (a finalized version is bumped first), is recorded as a preview change for the owner to approve, and is logged.
 * Artifacts are keyed by name, so sending the same name again replaces it (safe to retry).
 */
type Json = Record<string, any>;

export class ImportError extends AuthError {
  constructor(message: string, public errors: string[]) {
    super(400, "INVALID_DESIGN", message);
    Object.setPrototypeOf(this, ImportError.prototype);
  }
}

const REL_TYPES = ["include", "extend", "generalization"];
const NODE_TYPES = ["start", "end", "action", "decision", "merge", "fork", "join", "object"];
const MSG_TYPES = ["sync", "async", "reply", "create", "destroy"];
const FRAGMENT_TYPES = ["loop", "alt", "opt", "par", "region", "else"];
const DB_REL_TYPES = ["one-to-one", "one-to-many", "many-to-one", "many-to-many"];

const asArray = (v: unknown): any[] => (Array.isArray(v) ? v : []);
const str = (v: unknown) => (typeof v === "string" ? v.trim() : "");

export class ImportService {
  private versions = new VersionService();
  private logs = new LogService();
  private tableRules = new TableValidationService();
  private usecases = new UsecaseService();

  /** The version an edit must go to: a finalized version is first bumped to a working copy. */
  private async workingVersion(versionId: string, userId: string): Promise<{ id: string; project: string; number: string }> {
    let version: any = await Version.findById(versionId);
    if (!version) throw new AuthError(404, "VERSION_NOT_FOUND", "Version not found");
    if (version.version_temporary === false) {
      const bumped = await this.versions.bumpVersion(versionId, userId, "minor");
      if (!bumped.data) throw new Error("Auto bump failed");
      version = bumped.data.newVersion;
    }
    return { id: String(version._id), project: String(version.project_id), number: String(version.version_number) };
  }

  private async record(userId: string, v: { id: string; project: string; number: string }, entity: "database" | "usecase_diagram" | "sequence_diagram" | "activity_diagram",
    doc: any, before: any | null, target: string) {
    await this.versions.createOrUpdatePreview(v.id, userId, {
      entity_type: entity, entity_id: String(doc._id), change_type: before ? "updated" : "added", before_snapshot: before, after_snapshot: doc.toObject ? doc.toObject() : doc,
    });
    const user: any = await User.findById(userId).select("name").lean();
    await this.logs.createLog({
      project_id: v.project, user_id: userId, action: "generate_output", target_id: String(doc._id), target_type: target, version_number: v.number,
      affects_requirement: true, level: "info", performed_by_ai: true,
      details: { message: `${user?.name ?? "User"} imported ${target} "${doc.name}" (written by an AI client)` },
    } as any);
  }

  private fail(errors: string[]): never {
    throw new ImportError(`Dữ liệu thiết kế không hợp lệ (${errors.length} lỗi): ${errors.slice(0, 8).join("; ")}`, errors);
  }

  // ---------------------------------------------------------------- use cases (many at once)
  /** Adds (or, for a name that already exists in the working version, replaces) use cases; the version is bumped once. */
  async importUsecases(userId: string, versionId: string, body: Json) {
    const items = asArray(body.usecases);
    if (!items.length) this.fail(["usecases phải có ít nhất một use case"]);
    const early: string[] = [];
    items.forEach((u: Json, i: number) => {
      if (!str(u.name)) early.push(`use case ${i + 1}: thiếu name`);
      if (!asArray(u.main_flow).length) early.push(`use case "${u.name ?? i + 1}": main_flow cần ít nhất một bước`);
      asArray(u.main_flow).forEach((st: Json, k: number) => {
        if (!str(st?.action)) early.push(`use case "${u.name ?? i + 1}": bước ${k + 1} của main_flow thiếu action`);
      });
    });
    if (early.length) this.fail(early);

    const v = await this.workingVersion(versionId, userId);
    const created: { name: string; id: string }[] = [];
    const replaced: { name: string; id: string }[] = [];
    const failed: { name: string; error: string }[] = [];
    for (const u of items) {
      const name = str(u.name);
      const dto = { ...u, name, actor: typeof u.actor === "string" ? { name: u.actor } : u.actor ?? { name: "User" } };
      const existing: any = await Usecase.findOne({ version_id: v.id, name }).select("_id").lean();
      const result: any = existing
        ? await this.usecases.updateUsecaseInVersion(v.id, String(existing._id), userId, dto)
        : await this.usecases.addUsecaseToVersion(v.id, userId, dto);
      if (result?.success) {
        const doc = result.data?.usecase ?? result.data;
        const row = { name, id: String(doc?._id ?? existing?._id ?? "") };
        (existing ? replaced : created).push(row);
      } else {
        failed.push({ name, error: String(result?.message ?? "lỗi không rõ") });
      }
    }
    return { versionId: v.id, created, replaced, failed };
  }

  // ---------------------------------------------------------------- database design
  async importDatabase(userId: string, versionId: string, body: Json) {
    const errors: string[] = [];
    const name = str(body.name);
    if (!name) errors.push("name là bắt buộc");
    const tables = asArray(body.tables);
    if (!tables.length) errors.push("tables phải có ít nhất một bảng");
    const names = new Set<string>();
    const cleanTables: Json[] = tables.map((t, ti) => {
      const columns = asArray(t.columns).map((c: Json) => ({
        name: str(c.name), type: str(c.type) || "varchar", length: c.length != null ? String(c.length) : undefined,
        nullable: c.nullable === undefined ? !c.is_primary_key : !!c.nullable, unique: !!c.unique,
        is_primary_key: !!c.is_primary_key, is_foreign_key: !!c.is_foreign_key,
        references: c.references ? String(c.references).split(".")[0] : undefined, // "users.id" → "users"
        default: c.default != null ? String(c.default) : undefined,
        related_usecase_ids: asArray(c.related_usecase_ids).map(String), primary_key_order: c.primary_key_order ?? null,
      }));
      const table = { name: str(t.name), description: str(t.description), columns, position: { x: (ti % 4) * 320, y: Math.floor(ti / 4) * 280 } };
      try {
        this.tableRules.validateTableStructure(table as any);
      } catch (e: any) {
        errors.push(`bảng "${table.name || ti}": ${e.message}`);
      }
      if (names.has(table.name.toLowerCase())) errors.push(`tên bảng trùng: ${table.name}`);
      names.add(table.name.toLowerCase());
      return table;
    });
    for (const t of cleanTables) {
      for (const c of t.columns) {
        if (c.is_foreign_key && !c.references) errors.push(`${t.name}.${c.name} là khóa ngoại nhưng thiếu references`);
        if (c.references && !names.has(String(c.references).toLowerCase())) errors.push(`${t.name}.${c.name} tham chiếu bảng "${c.references}" không tồn tại`);
      }
    }
    // relationships: given, or derived from the foreign keys
    let relationships = asArray(body.relationships).map((r: Json) => ({ from_table: str(r.from_table), to_table: str(r.to_table), type: str(r.type) || "many-to-one" }));
    if (!relationships.length) {
      for (const t of cleanTables) for (const c of t.columns) if (c.is_foreign_key && c.references) relationships.push({ from_table: t.name, to_table: c.references, type: "many-to-one" });
    }
    for (const r of relationships) {
      if (!DB_REL_TYPES.includes(r.type)) errors.push(`relationship ${r.from_table}→${r.to_table}: type phải là ${DB_REL_TYPES.join("|")}`);
      if (!names.has(r.from_table.toLowerCase()) || !names.has(r.to_table.toLowerCase())) errors.push(`relationship ${r.from_table}→${r.to_table} trỏ tới bảng không tồn tại`);
    }
    if (errors.length) this.fail(errors);

    const v = await this.workingVersion(versionId, userId);
    const existing: any = await DatabaseModel.findOne({ version_id: v.id, name });
    const before = existing ? existing.toObject() : null;
    const doc: any = existing ?? new DatabaseModel({ project_id: v.project, version_id: v.id, name, generated_by: userId });
    doc.description = str(body.description);
    doc.tables = cleanTables;
    doc.relationships = relationships;
    doc.updated_at = new Date();
    await doc.save();
    await this.record(userId, v, "database", doc, before, "databases");
    return { versionId: v.id, id: String(doc._id), replaced: !!existing, tables: cleanTables.length, relationships: relationships.length };
  }

  // ---------------------------------------------------------------- use case diagram
  async importUsecaseDiagram(userId: string, versionId: string, body: Json) {
    const errors: string[] = [];
    const name = str(body.name);
    if (!name) errors.push("name là bắt buộc");
    const actors = asArray(body.actors).map((a: any) => (typeof a === "string" ? { name: a } : a)).map((a: Json, i: number) => ({
      _id: new Types.ObjectId(), name: str(a.name), description: str(a.description), position: { x: 60, y: 80 + i * 150 },
    }));
    const usecases = asArray(body.usecases).map((u: any) => (typeof u === "string" ? { title: u } : u)).map((u: Json, i: number) => ({
      _id: new Types.ObjectId(), title: str(u.title ?? u.name), description: str(u.description), position: { x: 420 + (i % 2) * 260, y: 60 + Math.floor(i / 2) * 110 },
    }));
    if (!actors.length) errors.push("actors phải có ít nhất một tác nhân");
    if (!usecases.length) errors.push("usecases phải có ít nhất một use case");
    if (actors.some((a) => !a.name) || usecases.some((u) => !u.title)) errors.push("mỗi actor cần name, mỗi use case cần title");
    const actorId = new Map(actors.map((a) => [a.name.toLowerCase(), a._id]));
    const ucId = new Map(usecases.map((u) => [u.title.toLowerCase(), u._id]));
    const associations = asArray(body.associations).flatMap((x: Json) => {
      const a = actorId.get(str(x.actor).toLowerCase()), u = ucId.get(str(x.usecase).toLowerCase());
      if (!a || !u) { errors.push(`association ${x.actor}—${x.usecase}: actor hoặc use case không có trong danh sách`); return []; }
      return [{ actor_id: a, usecase_id: u }];
    });
    const relationships = asArray(body.relationships).flatMap((x: Json) => {
      const s = ucId.get(str(x.source).toLowerCase()), t = ucId.get(str(x.target).toLowerCase());
      if (!s || !t) { errors.push(`relationship ${x.source}→${x.target}: use case không có trong danh sách`); return []; }
      if (!REL_TYPES.includes(str(x.type))) { errors.push(`relationship ${x.source}→${x.target}: type phải là ${REL_TYPES.join("|")}`); return []; }
      return [{ source: s, target: t, type: str(x.type) }];
    });
    if (errors.length) this.fail(errors);

    const v = await this.workingVersion(versionId, userId);
    const existing: any = await UsecaseDiagram.findOne({ version_id: v.id, name });
    const before = existing ? existing.toObject() : null;
    const doc: any = existing ?? new UsecaseDiagram({ project_id: v.project, version_id: v.id, name, created_by: userId });
    Object.assign(doc, { actors, usecases, associations, relationships, related_requirements: asArray(body.related_requirements).map(String) });
    await doc.save();
    await this.record(userId, v, "usecase_diagram", doc, before, "usecase_diagrams");
    return { versionId: v.id, id: String(doc._id), replaced: !!existing };
  }

  // ---------------------------------------------------------------- sequence diagram
  async importSequenceDiagram(userId: string, versionId: string, body: Json) {
    const errors: string[] = [];
    const name = str(body.name);
    if (!name) errors.push("name là bắt buộc");
    const lifelines = asArray(body.lifelines).map((l: any) => (typeof l === "string" ? { name: l } : l)).map((l: Json, i: number) => ({
      _id: new Types.ObjectId(), name: str(l.name), position: { x: 80 + i * 220, y: 40 },
    }));
    if (lifelines.length < 2) errors.push("lifelines cần ít nhất 2 đối tượng");
    const lid = new Map(lifelines.map((l) => [l.name.toLowerCase(), l._id]));
    const fragmentDefs = asArray(body.fragments);
    const fragments = fragmentDefs.map((f: Json) => ({ _id: new Types.ObjectId(), key: str(f.key), type: str(f.type), guard_condition: str(f.guard ?? f.guard_condition), parent: str(f.parent) }));
    const fid = new Map(fragments.map((f) => [f.key, f._id]));
    for (const f of fragments) {
      if (!f.key) errors.push("mỗi fragment cần key");
      if (!FRAGMENT_TYPES.includes(f.type)) errors.push(`fragment ${f.key}: type phải là ${FRAGMENT_TYPES.join("|")}`);
      if (f.parent && !fid.has(f.parent)) errors.push(`fragment ${f.key}: parent "${f.parent}" không tồn tại`);
    }
    const messages = asArray(body.messages).flatMap((m: Json, i: number) => {
      const s = lid.get(str(m.from).toLowerCase()), t = lid.get(str(m.to).toLowerCase());
      const type = str(m.type) || "sync";
      if (!s || !t) { errors.push(`message ${i + 1}: "${m.from}" hoặc "${m.to}" không có trong lifelines`); return []; }
      if (!MSG_TYPES.includes(type)) { errors.push(`message ${i + 1}: type phải là ${MSG_TYPES.join("|")}`); return []; }
      if (!str(m.content)) { errors.push(`message ${i + 1}: thiếu content`); return []; }
      if (m.fragment && !fid.has(str(m.fragment))) { errors.push(`message ${i + 1}: fragment "${m.fragment}" không tồn tại`); return []; }
      return [{ source_lifeline_id: s, target_lifeline_id: t, order: i + 1, content: str(m.content), type, fragment_id: m.fragment ? fid.get(str(m.fragment)) : null, position: { y: 120 + i * 60 } }];
    });
    if (!messages.length) errors.push("messages phải có ít nhất một thông điệp");
    if (errors.length) this.fail(errors);

    const v = await this.workingVersion(versionId, userId);
    let ref: string | undefined;
    if (str(body.usecase)) {
      const uc: any = await Usecase.findOne({ version_id: v.id, name: str(body.usecase) }).select("_id").lean();
      ref = uc ? String(uc._id) : undefined;
    }
    const existing: any = await SequenceDiagram.findOne({ version_id: v.id, name });
    const before = existing ? existing.toObject() : null;
    const doc: any = existing ?? new SequenceDiagram({ project_id: v.project, version_id: v.id, name, created_by: userId });
    doc.description = str(body.description);
    doc.usecase_ref_id = ref ?? (str(body.usecase) || undefined);
    doc.lifelines = lifelines;
    doc.fragments = fragments.map((f) => ({ _id: f._id, type: f.type, guard_condition: f.guard_condition, parent_fragment_id: f.parent ? fid.get(f.parent) : null }));
    doc.messages = messages;
    await doc.save();
    await this.record(userId, v, "sequence_diagram", doc, before, "sequence_diagrams");
    return { versionId: v.id, id: String(doc._id), replaced: !!existing, linkedUseCase: !!ref };
  }

  // ---------------------------------------------------------------- activity diagram
  async importActivityDiagram(userId: string, versionId: string, body: Json) {
    const errors: string[] = [];
    const name = str(body.name);
    if (!name) errors.push("name là bắt buộc");
    const lanes = asArray(body.lanes).map((l: any) => (typeof l === "string" ? { name: l } : l)).map((l: Json) => ({ _id: new Types.ObjectId(), name: str(l.name) }));
    const laneId = new Map(lanes.map((l) => [l.name.toLowerCase(), l._id]));
    const nodeDefs = asArray(body.nodes);
    const nodes = nodeDefs.map((n: Json, i: number) => ({
      _id: new Types.ObjectId(), key: str(n.key), type: str(n.type), label: str(n.label), lane: str(n.lane), position: { x: 200 + (n.lane && laneId.size ? Array.from(laneId.keys()).indexOf(str(n.lane).toLowerCase()) : 0) * 300, y: 60 + i * 110 },
    }));
    if (nodes.length < 2) errors.push("nodes cần ít nhất 2 nút (start và end)");
    const keys = new Set<string>();
    for (const n of nodes) {
      if (!n.key) errors.push("mỗi node cần key (dùng trong edges)");
      if (keys.has(n.key)) errors.push(`node key trùng: ${n.key}`);
      keys.add(n.key);
      if (!NODE_TYPES.includes(n.type)) errors.push(`node ${n.key}: type phải là ${NODE_TYPES.join("|")}`);
      if (n.lane && !laneId.has(n.lane.toLowerCase())) errors.push(`node ${n.key}: lane "${n.lane}" không có trong lanes`);
    }
    if (!nodes.some((n) => n.type === "start")) errors.push("thiếu node type start");
    if (!nodes.some((n) => n.type === "end")) errors.push("thiếu node type end");
    const nid = new Map(nodes.map((n) => [n.key, n._id]));
    const edges = asArray(body.edges).flatMap((e: Json, i: number) => {
      const f = nid.get(str(e.from)), t = nid.get(str(e.to));
      if (!f || !t) { errors.push(`edge ${i + 1}: "${e.from}" hoặc "${e.to}" không phải node key`); return []; }
      return [{ from: f, to: t, condition: str(e.condition) || undefined, guard: str(e.guard) || undefined, trigger: str(e.trigger) || undefined }];
    });
    if (nodes.length > 1 && !edges.length) errors.push("edges phải nối các node");
    if (errors.length) this.fail(errors);

    const v = await this.workingVersion(versionId, userId);
    const existing: any = await ActivityDiagram.findOne({ version_id: v.id, name });
    const before = existing ? existing.toObject() : null;
    const doc: any = existing ?? new ActivityDiagram({ project_id: v.project, version_id: v.id, name, created_by: userId });
    doc.description = str(body.description);
    doc.lanes = lanes;
    doc.nodes = nodes.map((n) => ({ _id: n._id, type: n.type, label: n.label || (n.type === "start" ? "Bắt đầu" : n.type === "end" ? "Kết thúc" : n.key), lane_id: n.lane ? laneId.get(n.lane.toLowerCase()) : null, position: n.position }));
    doc.edges = edges;
    await doc.save();
    await this.record(userId, v, "activity_diagram", doc, before, "activity_diagrams");
    return { versionId: v.id, id: String(doc._id), replaced: !!existing, nodes: nodes.length, edges: edges.length };
  }
}
